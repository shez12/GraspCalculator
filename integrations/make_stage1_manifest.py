#!/usr/bin/env python3
"""Build the Stage 1 subset manifest (1 representative object per category) from
the full OakInk manifest generated by `prepare_oakink_assets.py`.

Each category selects the exact object used by its category MANO reference in
`refs_by_cat/index.json` (falling back to the first asset in that category if
the exact ref object is absent), reusing the existing baked USD cache.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--full_manifest",
        required=True,
        help="Path to full manifest.json produced by prepare_oakink_assets.py",
    )
    p.add_argument(
        "--ref_index",
        default=str(Path(__file__).resolve().parent.parent / "refs_by_cat" / "index.json"),
        help="Path to refs_by_cat/index.json",
    )
    p.add_argument(
        "--out_manifest",
        required=True,
        help="Output path for Stage 1 subset manifest JSON",
    )
    p.add_argument(
        "--out_clouds",
        required=True,
        help="Output path for Stage 1 subset point-cloud cache (.pt)",
    )
    args = p.parse_args()

    full_m = json.loads(Path(args.full_manifest).read_text())
    ref_idx = json.loads(Path(args.ref_index).read_text()) if Path(args.ref_index).exists() else {}
    clouds = torch.load(full_m["pointcloud_cache"], map_location="cpu")

    assets = full_m["assets"]
    by_cat: dict[str, list[int]] = {}
    for i, a in enumerate(assets):
        by_cat.setdefault(a["category"], []).append(i)

    chosen_indices: list[int] = []
    chosen_assets: list[dict] = []
    categories = sorted(by_cat.keys())
    for cat in categories:
        ref_obj = None
        if cat in ref_idx:
            ref_entry = ref_idx[cat]
            ref_id = ref_entry.get("ref") or ref_entry.get("ref_id") or ""
            ref_obj = ref_entry.get("obj_id") or (ref_id.split("/")[0] if "/" in ref_id else None)
        pick = by_cat[cat][0]
        if ref_obj is not None:
            for idx in by_cat[cat]:
                if assets[idx].get("obj_id") == ref_obj:
                    pick = idx
                    break
        chosen_indices.append(pick)
        chosen_assets.append(assets[pick])

    idx_t = torch.tensor(chosen_indices, dtype=torch.long)
    sub_clouds = {
        "points": clouds["points"][idx_t],
        "afford_mask": clouds["afford_mask"][idx_t],
        "asset_ids": [clouds["asset_ids"][i] for i in chosen_indices],
        "categories": categories,
        "category_ids": torch.arange(len(categories), dtype=torch.long),
    }
    for extra_k in ("normals", "part_ids", "scales"):
        if extra_k in clouds and torch.is_tensor(clouds[extra_k]) and clouds[extra_k].shape[0] == len(assets):
            sub_clouds[extra_k] = clouds[extra_k][idx_t]

    out_clouds = Path(args.out_clouds).resolve()
    out_manifest = Path(args.out_manifest).resolve()
    out_clouds.parent.mkdir(parents=True, exist_ok=True)
    out_manifest.parent.mkdir(parents=True, exist_ok=True)

    torch.save(sub_clouds, out_clouds)
    sub_manifest = dict(full_m)
    sub_manifest["assets"] = chosen_assets
    sub_manifest["pointcloud_cache"] = str(out_clouds)
    out_manifest.write_text(json.dumps(sub_manifest, indent=2))

    print(f"Wrote {len(chosen_assets)} assets ({len(categories)} categories) -> {out_manifest}")
    for a in chosen_assets:
        print(f"  {a['category']:16s}  {a['obj_id']}")


if __name__ == "__main__":
    main()
